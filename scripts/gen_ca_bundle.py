#!/usr/bin/env python3
"""Pack a PEM root list into the CA bundle format read by the Arduino core's esp_crt_bundle.c (GM-296)."""
import argparse
import base64
import os
import re
import sys

PEM_RE = re.compile(rb"-----BEGIN CERTIFICATE-----(.+?)-----END CERTIFICATE-----", re.S)
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME_OIDS = {b"\x55\x04\x03": "CN", b"\x55\x04\x0a": "O", b"\x55\x04\x0b": "OU"}


def read_tlv(buf, pos):
    """Return (tag, value_start, end) of the DER element at pos."""
    tag = buf[pos]
    length = buf[pos + 1]
    pos += 2
    if length & 0x80:
        count = length & 0x7F
        length = int.from_bytes(buf[pos : pos + count], "big")
        pos += count
    return tag, pos, pos + length


def subject_and_key(der):
    """Return the raw subject Name and SubjectPublicKeyInfo of a DER certificate."""
    _, cert_start, _ = read_tlv(der, 0)
    _, pos, _ = read_tlv(der, cert_start)
    tag, _, end = read_tlv(der, pos)
    if tag == 0xA0:  # explicit version
        pos = end
    fields = []
    for _ in range(6):  # serial, signature, issuer, validity, subject, key
        _, _, end = read_tlv(der, pos)
        fields.append(der[pos:end])
        pos = end
    return fields[4], fields[5]


def display_name(name):
    """Return the most specific readable attribute of a DER Name."""
    found = {}
    _, pos, end = read_tlv(name, 0)
    while pos < end:
        _, rdn_start, rdn_end = read_tlv(name, pos)
        _, atv_start, _ = read_tlv(name, rdn_start)
        _, oid_start, oid_end = read_tlv(name, atv_start)
        _, val_start, val_end = read_tlv(name, oid_end)
        key = NAME_OIDS.get(name[oid_start:oid_end])
        if key:
            found[key] = name[val_start:val_end].decode("utf-8", "replace")
        pos = rdn_end
    return found.get("CN") or found.get("OU") or found.get("O") or "?"


def load_roots(pem_path):
    """Return {subject: key} for every certificate in the PEM file."""
    with open(pem_path, "rb") as f:
        blocks = PEM_RE.findall(f.read())
    roots = {}
    for block in blocks:
        subject, key = subject_and_key(base64.b64decode(block))
        if roots.setdefault(subject, key) != key:
            sys.exit(f"gen_ca_bundle: two keys for subject '{display_name(subject)}'; the lookup can only hold one")
    if not roots:
        sys.exit(f"gen_ca_bundle: no certificates in {pem_path}")
    return roots


def pack(roots):
    """Serialize roots sorted by subject, the order the firmware's binary search expects."""
    out = bytearray(len(roots).to_bytes(2, "big"))
    for subject in sorted(roots):
        key = roots[subject]
        out += len(subject).to_bytes(2, "big") + len(key).to_bytes(2, "big") + subject + key
    return bytes(out)


def render_c(bundle, pem_path):
    rows = [", ".join(f"0x{b:02x}" for b in bundle[i : i + 16]) for i in range(0, len(bundle), 16)]
    body = ",\n".join("    " + row for row in rows)
    return (
        f"// Generated by scripts/gen_ca_bundle.py from {pem_path}; do not edit.\n"
        "// clang-format off\n"
        '#include "ca_bundle.h"\n\n'
        f"const uint8_t gm_ca_bundle[] = {{\n{body},\n}};\n"
    )


def write_if_changed(path, text):
    if os.path.isfile(path):
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return False
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pem", help="PEM file with the trusted roots")
    parser.add_argument("--out", help="C source to write")
    parser.add_argument("--bin", help="raw bundle to write")
    parser.add_argument("--list", action="store_true", help="print the roots in bundle order")
    args = parser.parse_args()

    roots = load_roots(args.pem)
    bundle = pack(roots)
    if args.list:
        for subject in sorted(roots):
            print(display_name(subject))
    if args.bin:
        with open(args.bin, "wb") as f:
            f.write(bundle)
    if args.out:
        label = os.path.relpath(os.path.abspath(args.pem), REPO_ROOT).replace(os.sep, "/")
        changed = write_if_changed(args.out, render_c(bundle, label))
        print(f"gen_ca_bundle: {len(roots)} roots, {len(bundle)} bytes ({'updated' if changed else 'unchanged'})")


if __name__ == "__main__":
    main()
